/**
 * WorldBookAuditService —— 世界书编写智能体审计服务
 *
 * 来源：spec §二 Task 2 / `implement-worldbook-authoring-agent`
 * 决策：自研（spec §三无对应 openclaw 文件）。审计服务复用现有底座：
 *       EmbeddingService（向量化）/ AIService（LLM 语义对比）。
 *
 * 职责：
 *  1. validateCompleteness：必填字段 + 维度覆盖 + 条目数达标（80% 阈值）
 *  2. checkConsistency：关键词冲突（cosine 复验）+ 设定矛盾（LLM 对比）+ 关系图无环（DFS）
 *  3. evaluateConformance：用户提示 + 澄清回答与条目的语义一致性（cosine 相似度）
 *  4. runFullAudit：聚合三维度 + 自动修复建议 + 用户决策项
 *
 * 设计约束：
 *  - 错误隔离：每维度独立 try-catch，单维度失败不阻塞其他维度（降级返回部分报告 + warn 日志）
 *  - 依赖注入：EmbeddingService / LLMCompareFn 可通过构造参数注入，便于测试 mock
 *    （LLM 调用：复用 AIService 的 streamChatAPI；若不便于直接调用，定义 LLMCompareFn 注入点）
 *  - 字段标准：对齐 `worldBookService.migrateEntry` ——
 *    · key: string[]（非空数组，每元素非空字符串）
 *    · content: string（非空）
 *    · comment 或 name: string（至少一个非空）
 *  - 日志前缀：[WorldBookAuditService]
 *
 * 实现说明（向量化策略）：
 *  - 当前实现采用直接 cosine 计算（embeddingService.generateEmbedding + 内联 cosineSimilarity），
 *    而非 vectorStoreService.search，原因：
 *    1) 草稿区条目（autoGenerated=true）可能尚未写入向量库，无法通过 search 检索
 *    2) 直接 cosine 计算更易测试 mock，避免 sqlite-vec post-filter 语义限制
 *    3) 接口预留 IVectorStoreProvider，未来可扩展为优先查向量库、降级重新向量化
 */

